test('duas sessões da mesma conta convergem após reload sem compartilhar cache', async ({ browser }) => {
  const first = await browser.newContext()
  const second = await browser.newContext()
  try {
    const api = await backend(first)
    await backend(second, api.rows)
    await seed(first)
    await seed(second)
    const a = await first.newPage()
    const b = await second.newPage()
    await a.goto('/')
    await login(a)
    await synced(a)
    await status(a).selectOption('studying')
    await synced(a)
    await b.goto('/')
    await login(b)
    await synced(b)
    await expect(status(b)).toHaveValue('studying')
    await status(b).selectOption('done')
    await synced(b)
    await a.reload()
    await synced(a)
    await expect(status(a)).toHaveValue('done')
  } finally { await first.close(); await second.close() }
})

test('sessão expirada volta a visitante preservando o último progresso', async ({ page, context }) => {
  const api = await backend(context)
  await seed(context)
  await page.goto('/')
  await login(page)
  await synced(page)
  await status(page).selectOption('planned')
  await synced(page)
  api.expire()
  await page.evaluate(() => {
    const storageKey = 'sb-quality-auth-token'
    const session = JSON.parse(localStorage.getItem(storageKey) ?? '')
    session.expires_at = 0
    localStorage.setItem(storageKey, JSON.stringify(session))
  })
  const count = api.requests.length
  await page.reload()
  await expect(page.getByText('Modo visitante', { exact: true })).toBeVisible()
  await expect(status(page)).toHaveValue('planned')
  await status(page).selectOption('studying')
  await expect(status(page)).toHaveValue('studying')
  expect(api.requests).toHaveLength(count)
})

